_SVG_ATTRS = {"xmlns": "http://www.w3.org/2000/svg", "fill": "none",
              "stroke": "currentColor", "stroke_width": "2", "stroke_linecap": "round",
              "stroke_linejoin": "round"}


def icon(name: str, size: float | str = 1, *, hidden: bool = True) -> Admitted:
    """The inline SVG for icon ``name``, ``size`` em wide and high (a number of em, or any CSS
    length as a string). It is decorative (``aria-hidden``): the control around it carries the
    accessible name; pass ``hidden=False`` when a wrapper already hides it. An unknown name raises
    ``ValueError`` naming the icons there are, so a typo fails the first time the page is built
    rather than drawing nothing."""
    try:
        shapes = _ICONS[name]
    except KeyError:
        raise ValueError(f"Unknown icon {name!r}; the icons are: {', '.join(_ICONS)}") from None
    length = f"{size}em" if isinstance(size, (int, float)) else size
    svg = Svg(shapes, width=length, height=length, **_SVG_ATTRS, **({"aria_hidden": "true"} if hidden else {}))
    # FastHTML lowercases keyword attribute names, and viewBox is case-sensitive wherever the
    # markup is read as XML, so it is set on the element as written.
    svg.attrs["viewBox"] = "0 0 24 24"
    return to_markup(svg)


def icon_names() -> tuple[str, ...]:
    """Every icon ``icon`` can draw."""
    return tuple(_ICONS)


def import_icon() -> Span:
    """The spreadsheet icon, placed as the first child of an import button."""
    return Span(icon("file-spreadsheet", hidden=False), cls="import-icon", aria_hidden="true")
