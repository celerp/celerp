"""The way back from every change the assistant can make.

Each write tool, keyed by its route (method, path), names how a user undoes it:

- ``tool:METHOD /path``: another assistant tool reverses it (for an edit, the same
  route with the earlier value, which the card shows).
- ``screen:/path``: the way back needs a secret the user types on that screen, so it
  never goes through the chat.
- ``reason:<key>``: there is no reverse, for the reason in ``REASONS``.

A reason must stand on its own; one that only points at the screen is refused
(``SCREEN_ONLY``). Generated data; tests check every compiled write tool has an entry.
"""

